// Concatenate src/ into one userscript that also works when pasted into the DevTools console.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const parts = ['core.js', 'store.js', 'net.js', 'ui.js', 'main.js']
  .map(f => `// ---- src/${f} ----\n${readFileSync(join(root, 'src', f), 'utf8')}`);

const header = `// ==UserScript==
// @name         GenCull: ChatGPT storage deduplicator
// @namespace    https://github.com/marsrobertson/version-manager-deduplicator-for-generative-AI
// @version      ${version}
// @description  Find repeat uploads and reference images in ChatGPT storage, cull failed generations, free up your quota. Runs locally in your ChatGPT tab.
// @match        https://chatgpt.com/*
// @run-at       document-start
// @grant        none
// @noframes
// ==/UserScript==
`;

const body = `${header}
// Built from src/ by scripts/build.mjs. Do not edit this file by hand.
(() => {
  'use strict';
  if (window.__gencullLoaded) { console.info('GenCull is already running in this tab.'); return; }
  window.__gencullLoaded = true;
${parts.join('\n').replaceAll('__VERSION__', version)}
})();
`;

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'gencull.user.js'), body);
console.log(`dist/gencull.user.js  ${(body.length / 1024).toFixed(1)} KB  v${version}`);
